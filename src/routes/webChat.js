        '#inputBar { display: flex; gap: 8px; padding: 14px 20px; border-top: 1px solid var(--border); flex-shrink: 0; align-items: center; z-index: 10; background: var(--bg); padding-bottom: calc(14px + env(safe-area-inset-bottom)); }',
