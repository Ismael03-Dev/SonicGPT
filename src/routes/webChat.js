function renderChatPage() {
    var html = [
        '<!DOCTYPE html>',
        '<html lang="fr">',
        '<head>',
        '<meta charset="UTF-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1.0">',
        '<title>SonicGPT</title>',
        '<style>',
        ':root { --bg: #0f1117; --bg-soft: #1c1e29; --border: #23252e; --text: #e8e8ea; --accent: #7c5cff; --danger: #ff6b6b; }',
        '* { box-sizing: border-box; }',
        'body { margin: 0; font-family: sans-serif; background: var(--bg); color: var(--text); height: 100vh; height: 100dvh; display: flex; flex-direction: column; overflow: hidden; }',
        'header { padding: 16px 20px; border-bottom: 1px solid var(--border); display: flex; justify-content: space-between; align-items: center; flex-shrink: 0; }',
        'h1 { font-size: 18px; margin: 0; color: var(--accent); }',
        '#messages { flex: 1; overflow-y: auto; padding: 20px; display: flex; flex-direction: column; gap: 16px; }',
        '.bubble { max-width: 85%; line-height: 1.6; font-size: 15px; word-wrap: break-word; }',
        '.user { align-self: flex-end; background: var(--accent); color: white; padding: 10px 16px; border-radius: 18px; border-bottom-right-radius: 4px; }',
        '.bot { align-self: flex-start; background: transparent; padding: 4px 0; max-width: 100%; }',
        '.error-bubble { border-left: 3px solid var(--danger); padding-left: 10px; }',
        '.status { align-self: flex-start; color: #7a7d94; font-size: 13px; font-style: italic; }',
        '#inputBar { display: flex; gap: 8px; padding: 14px 20px; border-top: 1px solid var(--border); flex-shrink: 0; align-items: center; z-index: 10; background: var(--bg); }',
        '#textInput { flex: 1; background: var(--bg-soft); border: 1px solid var(--border); color: var(--text); padding: 12px 16px; border-radius: 12px; font-size: 15px; outline: none; }',
        '.iconBtn { background: var(--bg-soft); border: 1px solid var(--border); color: var(--text); width: 42px; height: 42px; border-radius: 12px; cursor: pointer; font-size: 16px; }',
        '#sendBtn { background: var(--accent); border: none; color: white; padding: 0 20px; height: 42px; border-radius: 12px; cursor: pointer; font-size: 15px; }',
        '</style>',
        '</head>',
        '<body>',
        '<header><h1>SonicGPT</h1><button id="resetBtn">Réinitialiser</button></header>',
        '<div id="messages"></div>',
        '<div id="inputBar">',
        '<input type="file" id="fileInput" accept="image/*" style="display:none">',
        '<button class="iconBtn" id="attachBtn">📎</button>',
        '<input id="textInput" type="text" placeholder="Écris à SonicGPT...">',
        '<button id="sendBtn">Envoyer</button>',
        '</div>',
        '<script>',
        'var messagesEl = document.getElementById("messages");',
        'var textInput = document.getElementById("textInput");',
        'var sendBtn = document.getElementById("sendBtn");',
        'var resetBtn = document.getElementById("resetBtn");',
        'var attachBtn = document.getElementById("attachBtn");',
        'var fileInput = document.getElementById("fileInput");',
        'var conversationId = localStorage.getItem("sonicgpt_conversation_id");',
        'var ownerId = localStorage.getItem("sonicgpt_owner_id");',
        'if (!ownerId) { ownerId = "web-" + Date.now(); localStorage.setItem("sonicgpt_owner_id", ownerId); }',
        'function addBubble(role, text) {',
        '  var el = document.createElement("div");',
        '  el.className = "bubble " + role;',
        '  el.textContent = text;',
        '  messagesEl.appendChild(el);',
        '  messagesEl.scrollTop = messagesEl.scrollHeight;',
        '  return el;',
        '}',
        'async function ensureConv() {',
        '  if (conversationId) return conversationId;',
        '  var res = await fetch("/public/v1/conversations", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ model: "sonicgpt-1", ownerId: ownerId }) });',
        '  if (!res.ok) throw new Error("Erreur création");',
        '  var data = await res.json();',
        '  conversationId = data.id;',
        '  localStorage.setItem("sonicgpt_conversation_id", conversationId);',
        '  return conversationId;',
        '}',
        'async function envoyer() {',
        '  var text = textInput.value.trim();',
        '  if (!text) return;',
        '  textInput.value = "";',
        '  sendBtn.disabled = true;',
        '  addBubble("user", text);',
        '  var statusEl = addBubble("status", "SonicGPT réfléchit...");',
        '  try {',
        '    var convId = await ensureConv();',
        '    var res = await fetch("/public/v1/conversations/" + convId + "/messages", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ content: text, stream: false, callerId: ownerId, webAccess: true, source: "web" }) });',
        '    if (!res.ok) throw new Error("Erreur serveur (" + res.status + ")");',
        '    var data = await res.json();',
        '    statusEl.remove();',
        '    var botEl = addBubble("bot", data.content || "");',
        '    if (data.media && data.media.length > 0) {',
        '      data.media.forEach(function(m) {',
        '        if (m.mediaType === "image") {',
        '          var img = document.createElement("img");',
        '          img.src = "data:" + m.mimeType + ";base64," + m.base64;',
        '          img.style.maxWidth = "100%";',
        '          img.style.borderRadius = "10px";',
        '          img.style.marginTop = "10px";',
        '          img.style.display = "block";',
        '          botEl.appendChild(img);',
        '        }',
        '      });',
        '    }',
        '  } catch (e) {',
        '    statusEl.remove();',
        '    addBubble("bot error-bubble", "❌ " + e.message);',
        '  } finally {',
        '    sendBtn.disabled = false;',
        '    textInput.focus();',
        '  }',
        '}',
        'sendBtn.onclick = envoyer;',
        'textInput.onkeydown = function(e) { if (e.key === "Enter") envoyer(); };',
        'resetBtn.onclick = function() { localStorage.removeItem("sonicgpt_conversation_id"); conversationId = null; messagesEl.innerHTML = ""; };',
        'attachBtn.onclick = function() { fileInput.click(); };',
        '<\/script>',
        '</body>',
        '</html>'
    ].join('\n');
    return html;
}
module.exports = { renderChatPage };